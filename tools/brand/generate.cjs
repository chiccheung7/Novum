#!/usr/bin/env node
/* Optional asset authoring tool; it is not part of the Android build. */
const fs = require('node:fs/promises');
const path = require('node:path');
let sharp;
try {
  sharp = require('sharp');
} catch {
  console.error('This optional tool needs sharp 0.35.5. See tools/brand/README.md.');
  process.exit(1);
}

const root = path.resolve(__dirname, '../..');
const res = path.join(root, 'app/src/main/res');
const sourcePath = path.join(__dirname, 'novum_brand_banner.svg');
const previewDir = path.join(root, 'build/brand-preview');
const densities = {
  mdpi: [80, 160, 90],
  hdpi: [120, 240, 135],
  xhdpi: [160, 320, 180],
  xxhdpi: [240, 480, 270],
  xxxhdpi: [320, 640, 360],
};

function attributes(tag) {
  return Object.fromEntries([...tag.matchAll(/([\w-]+)="([^"]*)"/g)].map(m => [m[1], m[2]]));
}

function vectorDocument(paths, comment) {
  return `<?xml version="1.0" encoding="utf-8"?>\n` +
    `<!-- ${comment} Generated by tools/brand/generate.cjs. -->\n` +
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n` +
    `    android:width="108dp"\n    android:height="108dp"\n` +
    `    android:viewportWidth="108"\n    android:viewportHeight="108">\n` +
    paths.join('\n') + '\n</vector>\n';
}

async function main() {
  const banner = await fs.readFile(sourcePath, 'utf8');
  const mark = banner.match(/<g\b[^>]*\bid="novum-mark"[^>]*>([\s\S]*?)<\/g>/)?.[1];
  const backgroundTag = banner.match(/<path\b[^>]*\bid="brand-background"[^>]*\/>/)?.[0];
  const background = backgroundTag && attributes(backgroundTag).fill;
  if (!mark || !/^#[\da-f]{6}$/i.test(background || '')) {
    throw new Error('Master SVG must contain novum-mark and a solid brand-background.');
  }
  const markPaths = [...mark.matchAll(/<path\b[^>]*\/>/g)].map(m => attributes(m[0]));
  if (!markPaths.length || markPaths.some(p => !p.d || !/^#[\da-f]{6}$/i.test(p.fill || ''))) {
    throw new Error('The mark must contain filled vector paths without embedded images or fonts.');
  }
  const androidPaths = markPaths.map(p =>
    `    <path\n        android:fillColor="${p.fill}"\n` +
    (p['fill-rule'] === 'evenodd' ? '        android:fillType="evenOdd"\n' : '') +
    `        android:pathData="${p.d}" />`,
  );
  const drawable = path.join(res, 'drawable');
  await fs.mkdir(drawable, { recursive: true });
  await fs.writeFile(path.join(drawable, 'ic_launcher_foreground.xml'),
    vectorDocument(androidPaths, 'Flat Novum projector mark.'));
  await fs.writeFile(path.join(drawable, 'ic_launcher_background.xml'),
    vectorDocument([`    <path android:fillColor="${background}" android:pathData="M0,0 H108 V108 H0 Z" />`],
      'Solid adaptive-icon background.'));

  const adaptive = `<?xml version="1.0" encoding="utf-8"?>\n` +
    `<!-- Generated from the same Novum brand master as all legacy icons and banners. -->\n` +
    `<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n` +
    `    <background android:drawable="@drawable/ic_launcher_background" />\n` +
    `    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n` +
    `    <monochrome android:drawable="@drawable/ic_launcher_foreground" />\n` +
    `</adaptive-icon>\n`;
  const adaptiveDir = path.join(res, 'mipmap-anydpi-v26');
  await fs.mkdir(adaptiveDir, { recursive: true });
  await fs.writeFile(path.join(adaptiveDir, 'ic_launcher.xml'), adaptive);
  await fs.writeFile(path.join(adaptiveDir, 'ic_launcher_round.xml'), adaptive);

  const iconContent =
    `<g transform="translate(54 54) scale(1.3) translate(-54 -54)">${mark}</g></svg>`;
  const icon = `<svg xmlns="http://www.w3.org/2000/svg" width="108" height="108" viewBox="0 0 108 108">` +
    `<rect x="4" y="4" width="100" height="100" rx="24" fill="${background}"/>` + iconContent;
  const roundIcon = `<svg xmlns="http://www.w3.org/2000/svg" width="108" height="108" viewBox="0 0 108 108">` +
    `<circle cx="54" cy="54" r="50" fill="${background}"/>` + iconContent;
  for (const [density, [iconSize, bannerWidth, bannerHeight]] of Object.entries(densities)) {
    const output = path.join(res, `mipmap-${density}`);
    await fs.mkdir(output, { recursive: true });
    await sharp(Buffer.from(icon), { density: 288 }).resize(iconSize, iconSize)
      .png({ compressionLevel: 9, effort: 10 }).toFile(path.join(output, 'ic_launcher.png'));
    await sharp(Buffer.from(roundIcon), { density: 288 }).resize(iconSize, iconSize)
      .png({ compressionLevel: 9, effort: 10 }).toFile(path.join(output, 'ic_launcher_round.png'));
    await sharp(Buffer.from(banner), { density: 144 }).resize(bannerWidth, bannerHeight).removeAlpha()
      .png({ compressionLevel: 9, effort: 10 }).toFile(path.join(output, 'app_banner.png'));
    console.log(`${density}: launcher + round ${iconSize}x${iconSize}, banner ${bannerWidth}x${bannerHeight}`);
  }
  await fs.mkdir(previewDir, { recursive: true });
  await fs.writeFile(path.join(previewDir, 'icon.svg'), icon);
  await fs.writeFile(path.join(previewDir, 'icon-round.svg'), roundIcon);
  await fs.writeFile(path.join(previewDir, 'banner.svg'), banner);
  await sharp(Buffer.from(icon), { density: 288 }).resize(320, 320).png()
    .toFile(path.join(previewDir, 'icon.png'));
  await sharp(Buffer.from(banner), { density: 144 }).resize(640, 360).removeAlpha().png()
    .toFile(path.join(previewDir, 'banner.png'));
  await sharp(Buffer.from(roundIcon), { density: 288 }).resize(320, 320).png()
    .toFile(path.join(previewDir, 'icon-round.png'));
  await sharp({ create: { width: 640, height: 680, channels: 3, background: '#22262C' } })
    .composite([
      { input: path.join(previewDir, 'icon.png'), left: 0, top: 0 },
      { input: path.join(previewDir, 'icon-round.png'), left: 320, top: 0 },
      { input: path.join(previewDir, 'banner.png'), left: 0, top: 320 },
    ]).png().toFile(path.join(previewDir, 'suite.png'));
  console.log(`Previews: ${previewDir}`);
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
